    private static void assertNear(int actualRgb, int expectedRgb, int tolerance, String where) {
        for (int shift : new int[] {16, 8, 0}) {
            int actual = (actualRgb >> shift) & 0xff;
            int expected = (expectedRgb >> shift) & 0xff;
            assertThat(actual)
                    .as("%s: %06x versus %06x", where, actualRgb & 0xffffff, expectedRgb)
                    .isBetween(expected - tolerance, expected + tolerance);
        }
    }

    private static String nearestColourName(int rgb, Map<String, Integer> colours) {
        String best = null;
        long bestDistance = Long.MAX_VALUE;
        for (Map.Entry<String, Integer> c : colours.entrySet()) {
            long d = 0;
            for (int shift : new int[] {16, 8, 0}) {
                long delta = ((rgb >> shift) & 0xff) - ((c.getValue() >> shift) & 0xff);
                d += delta * delta;
            }
            if (d < bestDistance) {
                bestDistance = d;
                best = c.getKey();
            }
        }
        return best;
    }

    /**
     * Where the point (x, y) of a STORED image of size w x h appears when viewed, written straight from the EXIF/TIFF specification's table
     * ("row 0 is the ... edge of the visible image"), independent of how the main code builds the transform.
     */
    private static int[] shownPosition(int orientation, int x, int y, int w, int h) {
        return switch (orientation) {
            case 1 -> new int[] {x, y};
            case 2 -> new int[] {w - 1 - x, y};
            case 3 -> new int[] {w - 1 - x, h - 1 - y};
            case 4 -> new int[] {x, h - 1 - y};
            case 5 -> new int[] {y, x};
            case 6 -> new int[] {h - 1 - y, x};
            case 7 -> new int[] {h - 1 - y, w - 1 - x};
            case 8 -> new int[] {y, w - 1 - x};
            default -> throw new IllegalArgumentException("orientation " + orientation);
        };
    }

