    @Test
    void phone_photo_orientation_6_is_made_upright_and_loses_all_exif_gps() throws Exception {
        byte[] input = fixture("orient6.jpg");
        // The input really carries EXIF (Orientation=6), GPS and ICC, and is STORED landscape with a red square in the
        // top-left corner.
        Metadata before = JpegMetadataReader.readMetadata(new ByteArrayInputStream(input));
        assertThat(before.getFirstDirectoryOfType(ExifIFD0Directory.class).getInt(ExifIFD0Directory.TAG_ORIENTATION))
                .isEqualTo(6);
        GpsDirectory gps = before.getFirstDirectoryOfType(GpsDirectory.class);
        assertThat(gps).isNotNull();
        assertThat(gps.getGeoLocation()).isNotNull();
        assertThat(jpegMetadataSegments(input)).contains(JpegSegmentType.APP1, JpegSegmentType.APP2);
        BufferedImage stored = decode(input);
        assertThat(stored.getWidth()).isEqualTo(30);
        assertThat(stored.getHeight()).isEqualTo(20);
        assertNear(stored.getRGB(0, 0), RED, "input: top-left corner");

        ProcessedImage out = processor.process(input);

        assertWellFormed(out, SPEC);
        assertThat(out.contentType()).isEqualTo("image/jpeg");
        assertThat(out.width()).isEqualTo(20);
        assertThat(out.height()).isEqualTo(30);
        // Orientation 6 means "rotate 90 degrees clockwise to view": the top-left corner when stored becomes the
        // top-right corner when viewed. Rotating the wrong way still gives 20x30, but the red square would sit in the
        // bottom-left corner.
        BufferedImage shown = decode(out.bytes());
        assertNear(shown.getRGB(19, 0), RED, "top-right corner");
        assertNear(shown.getRGB(0, 0), BLUE, "top-left corner");
        assertNear(shown.getRGB(0, 29), BLUE, "bottom-left corner");
        assertNear(shown.getRGB(19, 29), BLUE, "bottom-right corner");
        // Re-encoding wipes all metadata: no EXIF/GPS, no ICC, only the encoder's own APP0 (JFIF) remains.
        Metadata after = JpegMetadataReader.readMetadata(new ByteArrayInputStream(out.bytes()));
        assertThat(after.getFirstDirectoryOfType(GpsDirectory.class)).isNull();
        assertThat(after.getFirstDirectoryOfType(ExifIFD0Directory.class)).isNull();
        assertThat(jpegMetadataSegments(out.bytes())).containsOnly(JpegSegmentType.APP0);
    }

