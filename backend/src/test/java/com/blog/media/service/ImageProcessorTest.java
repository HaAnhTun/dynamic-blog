    @Test
    void oversized_progressive_or_multi_scan_jpeg_is_rejected_from_header_but_baseline_of_same_size_is_not()
            throws Exception {
        // A progressive or multi-scan image forces libjpeg to hold the DCT coefficients of the whole image in native
        // memory, and decoding with
        // skipped pixels does not reduce that: 3 bytes per pixel with 4:2:0. A 50 MP progressive JPEG of only 879 KB
        // was measured to allocate ~287 MB more.
        byte[] progressive = progressiveJpeg(quadrants(64, 48, RED, GREEN, BLUE, YELLOW));
        assertThat(sofMarker(progressive)).isEqualTo(0xC2);
        ProcessedImage ordinary = processor.process(progressive);
        assertWellFormed(ordinary, SPEC);
        assertThat(ordinary.width()).isEqualTo(64);

        // 6000x4000 at 4:2:0 needs 72 MB of coefficients, over the 64 MiB ceiling; the header is patched, so it is
        // rejected before decoding.
        byte[] baseline = jpeg(quadrants(64, 48, RED, GREEN, BLUE, YELLOW), 0.9f);
        long start = System.nanoTime();
        assertRejected(
                () -> processor.process(withSof(progressive, 0xC2, 6000, 4000)),
                ErrorCode.MEDIA_DIMENSIONS_TOO_LARGE,
                422);
        // A baseline whose first scan holds only one component is also a multi-scan image, also a whole-image buffer.
        assertRejected(
                () -> processor.process(withSingleComponentFirstScan(withSof(baseline, 0xC0, 6000, 4000))),
                ErrorCode.MEDIA_DIMENSIONS_TOO_LARGE,
                422);
        assertThat(Duration.ofNanos(System.nanoTime() - start)).isLessThan(Duration.ofSeconds(1));

        // Control: a 4000x3000 progressive (36 MB) under the ceiling, and a one-scan baseline 6000x4000 (libjpeg
        // decodes row by row,
        // without holding coefficients) both pass this gate. The pixel data does not match the patched header so the
        // decode result does not
        // matter here; it only has to not be rejected for its size.
        assertNotRejectedForSize(withSof(progressive, 0xC2, 4000, 3000));
        assertNotRejectedForSize(withSof(baseline, 0xC0, 6000, 4000));
    }

