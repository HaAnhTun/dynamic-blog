    @ParameterizedTest(name = "orientation {0}")
    @ValueSource(ints = {1, 2, 3, 4, 5, 6, 7, 8})
    void every_orientation_value_puts_each_corner_in_place_per_exif_spec(int orientation) throws Exception {
        // Four quadrants in four colors, so every flip and rotation can be told apart from the others.
        BufferedImage stored = quadrants(64, 32, RED, GREEN, BLUE, YELLOW);
        byte[] input = withExifApp1(jpeg(stored, 0.95f), exifOrientation(orientation));

        ProcessedImage out = processor.process(input);

        assertWellFormed(out, SPEC);
        boolean swapped = orientation >= 5;
        assertThat(out.width()).isEqualTo(swapped ? 32 : 64);
        assertThat(out.height()).isEqualTo(swapped ? 64 : 32);
        BufferedImage shown = decode(out.bytes());
        Map<String, int[]> centres = Map.of(
                "red", new int[] {16, 8}, "green", new int[] {48, 8}, "blue", new int[] {16, 24}, "yellow", new int[] {
                    48, 24
                });
        Map<String, Integer> colours = Map.of("red", RED, "green", GREEN, "blue", BLUE, "yellow", YELLOW);
        centres.forEach((name, p) -> {
            int[] q = shownPosition(orientation, p[0], p[1], 64, 32);
            assertThat(nearestColourName(shown.getRGB(q[0], q[1]), colours))
                    .as("cell %s stored at (%d,%d) must appear at (%d,%d)", name, p[0], p[1], q[0], q[1])
                    .isEqualTo(name);
        });
    }

