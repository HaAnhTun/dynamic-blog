/**
 * The site's public origin. One definition, because there were four.
 *
 * `app/sitemap.ts`, `app/robots.ts` and `components/site/ArticleJsonLd.tsx` each grew
 * their own copy of this, and each independently worked out that an empty
 * `NEXT_PUBLIC_SITE_URL=` line is not a configured origin — their comments say so. Then
 * `app/layout.tsx` wrote the fourth copy as `process.env.NEXT_PUBLIC_SITE_URL ?? '...'`,
 * which is the one version that gets it wrong.
 *
 * `??` falls back only on null and undefined. An empty string is neither, so with
 * `NEXT_PUBLIC_SITE_URL=` in a .env file — a completely ordinary way to write a line you
 * have not filled in yet — `siteUrl` becomes `''`, and `new URL('')` throws
 * `TypeError: Invalid URL`. In `metadataBase` that is thrown while generating metadata for
 * every route, so **every page on the site 500s**. It is reachable from this project's own
 * `frontend/Dockerfile`, which declares `ARG NEXT_PUBLIC_SITE_URL` and passes it through:
 * `docker compose build --build-arg NEXT_PUBLIC_SITE_URL=` is enough.
 *
 * Four copies of a rule is also how three of them end up right and one wrong without
 * anybody noticing, which is exactly what happened.
 *
 * Trailing slashes are stripped so that `${siteUrl()}/writing` cannot produce `//writing`,
 * and `https://example.com/` in a .env file is as likely as the version without.
 */
const FALLBACK = 'http://localhost:3000'

export function siteUrl(): string {
  // `||`, not `??`: the empty string must fall through to the default. That one character
  // is the whole reason this module exists.
  const configured = process.env.NEXT_PUBLIC_SITE_URL?.trim() || FALLBACK
  return configured.replace(/\/+$/, '')
}

/**
 * The same value as a `URL`, for `metadataBase`. Separate so a caller cannot forget the
 * constructor and so an invalid configured value fails here, with this message, rather
 * than as a bare `TypeError: Invalid URL` from inside Next's metadata generation.
 */
export function siteUrlObject(): URL {
  const value = siteUrl()
  try {
    return new URL(value)
  } catch {
    throw new Error(
      `NEXT_PUBLIC_SITE_URL is not a usable origin: ${JSON.stringify(value)}. ` +
        'It needs a scheme, e.g. https://example.com — a bare hostname will not parse.',
    )
  }
}

/** An absolute URL for a site-relative path. Accepts paths with or without a leading slash. */
export function absoluteUrl(path: string): string {
  if (path === '' || path === '/') return `${siteUrl()}/`
  return `${siteUrl()}/${path.replace(/^\/+/, '')}`
}

/**
 * The site-wide share card, generated by app/opengraph-image.tsx.
 *
 * It has to be stated explicitly in every page whose metadata exports its own
 * `openGraph` object, and that is a real Next behaviour rather than an oversight:
 * measured on the running site, /writing — the one public page with no `openGraph` of
 * its own — emitted og:image from the file convention, while / and /about and
 * every article did NOT. A segment's `openGraph` REPLACES the inherited one, images
 * included, so a page that sets a per-page title silently loses the image.
 *
 * The symptom is invisible on the site itself: `twitter:card` is declared
 * `summary_large_image`, so a share rendered a blank 1200x630 panel. Nothing fails, no
 * test sees it, and it only shows up in somebody else's timeline.
 *
 * Relative, because `metadataBase` in app/layout.tsx makes it absolute — and that is
 * also why it must not be built with absoluteUrl() here: two mechanisms producing the
 * same URL is how they come to disagree.
 */
export const OG_IMAGE = '/opengraph-image'

/**
 * The RSS feed, served by app/feed.xml/route.ts.
 *
 * Here beside OG_IMAGE rather than in the route, because two things need the string and
 * they are in different places: the route builds its own `<atom:link rel="self">` from it,
 * and lib/metadata.ts advertises it as `<link rel="alternate">` on every public page. A
 * feed whose self-link and whose discovery link disagree is a feed some readers subscribe
 * to twice.
 *
 * Relative, like OG_IMAGE, so `metadataBase` resolves it and the origin stays configured
 * in exactly one place.
 */
export const FEED_PATH = '/feed.xml'

/**
 * The own feed of a category, series or tag: `<page>/feed.xml`, slug encoded like the page's
 * href. Same reason as FEED_PATH: the route builds `<atom:link rel="self">` and the page builds the autodiscovery link
 * from one and the same function.
 */
export function categoryFeedPath(slug: string): string {
  return `/categories/${encodeURIComponent(slug)}${FEED_PATH}`
}

export function seriesFeedPath(slug: string): string {
  return `/series/${encodeURIComponent(slug)}${FEED_PATH}`
}

export function tagFeedPath(slug: string): string {
  return `/tags/${encodeURIComponent(slug)}${FEED_PATH}`
}
