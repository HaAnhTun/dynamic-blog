import { render, screen, within } from '@testing-library/react'
import { describe, expect, it } from 'vitest'
import { mediaPath } from '@/lib/media'
import type { GalleryPhoto } from '@/lib/types'
import { translatorFor } from '@/test/intl'
import {
  GalleryGrid,
  JUSTIFIED_MAX_GROWTH,
  TILE_INDEX_ATTRIBUTE,
  TILE_WIDTH,
  justifiedSizes,
  layoutRatio,
  photoName,
  tileSizes,
} from './GalleryGrid'
import { msg } from '@/test/render-intl'

/**
 * GalleryGrid is the server part of the gallery: a square 3-column grid, each cell a real
 * link to the original image. No JS needed: pressing a cell opens the image. GalleryLightbox (client) only intercepts that press
 * and opens the viewer instead — it finds the cell by `data-gallery-index`, so that attribute is a contract
 * between the two files and is pinned here.
 *
 * next/image is the real one, not a mock: `src` through mediaPath, `sizes`, `fill` are all generated by it.
 */

const uuid = (n: number) => `00000000-0000-4000-8000-${String(n).padStart(12, '0')}`

function photo(n: number, extra: Partial<GalleryPhoto['image']> = {}): GalleryPhoto {
  return {
    id: uuid(100 + n),
    image: {
      id: uuid(n),
      fileName: `${uuid(n)}.jpg`,
      width: 1600,
      height: 1200,
      altText: `Photo description number ${n}`,
      dominantColor: '#5a6b7c',
      ...extra,
    },
    caption: null,
    takenOn: null,
  }
}

const classesOf = (el: Element | null) => (el?.getAttribute('class') ?? '').split(/\s+/).filter(Boolean)

/** The `url` value that the default next/image loader writes into src: the path of the original image. */
const sourceOf = (img: HTMLImageElement) => new URL(img.getAttribute('src') ?? '', 'http://localhost').searchParams.get('url')

describe('GalleryGrid', () => {
  it('a square 3-column grid at every width, gap-1 then sm:gap-2', () => {
    const { container } = render(<GalleryGrid photos={[photo(1), photo(2), photo(3)]} />)

    const list = container.querySelector('ul')!
    expect(classesOf(list)).toEqual(expect.arrayContaining(['grid', 'grid-cols-3', 'gap-1', 'sm:gap-2']))
    // "Every width": no other column count at any breakpoint.
    expect(classesOf(list).filter((c) => c.includes('grid-cols-'))).toEqual(['grid-cols-3'])
    expect(list.querySelectorAll(':scope > li')).toHaveLength(3)
  })

  it('columns picks the grid classes: 3 always, 4 from xl (/gallery), 6 from lg (the photo bands); gap is unchanged', () => {
    const photos = [photo(1), photo(2), photo(3)]
    const gridClasses = (columns?: 3 | 4 | 6) => {
      const { container, unmount } = render(<GalleryGrid photos={photos} columns={columns} />)
      const classes = classesOf(container.querySelector('ul'))
      unmount()
      return classes
    }

    expect(gridClasses()).toEqual(['grid', 'grid-cols-3', 'gap-1', 'sm:gap-2'])
    expect(gridClasses(3)).toEqual(['grid', 'grid-cols-3', 'gap-1', 'sm:gap-2'])
    expect(gridClasses(4)).toEqual(['grid', 'grid-cols-3', 'xl:grid-cols-4', 'gap-1', 'sm:gap-2'])
    expect(gridClasses(6)).toEqual(['grid', 'grid-cols-3', 'lg:grid-cols-6', 'gap-1', 'sm:gap-2'])
  })

  it('each cell is <a href="/media/…"> to the original image, the accessible name is altText', () => {
    const photos = [photo(1), photo(2)]
    render(<GalleryGrid photos={photos} />)

    for (const p of photos) {
      // A real link: without JS, pressing it still opens the image. The path comes from mediaPath, not hand-built strings.
      expect(screen.getByRole('link', { name: p.image.altText! })).toHaveAttribute('href', mediaPath(p.image))
    }
    expect(screen.getAllByRole('link')).toHaveLength(2)
  })

  it('missing altText (null or only whitespace) gives the fallback name "Photo n" by position in the grid', () => {
    render(<GalleryGrid photos={[photo(1), photo(2, { altText: null }), photo(3, { altText: '   ' })]} />)

    expect(screen.getByRole('link', { name: msg('Site.gallery.photoName', { number: '2' }) })).toHaveAttribute(
      'href',
      mediaPath(photo(2).image),
    )
    expect(screen.getByRole('link', { name: msg('Site.gallery.photoName', { number: '3' }) })).toHaveAttribute(
      'href',
      mediaPath(photo(3).image),
    )
    // The "has one" pair: an image with a description keeps its description, it is not numbered.
    expect(screen.getByRole('link', { name: 'Photo description number 1' })).toBeInTheDocument()
    expect(screen.queryByRole('link', { name: msg('Site.gallery.photoName', { number: '1' }) })).not.toBeInTheDocument()

    const t = translatorFor('vi', 'Site.gallery')
    expect(photoName(photo(5, { altText: null }), 4, t)).toBe(msg('Site.gallery.photoName', { number: '5' }))
    expect(photoName(photo(5, { altText: '  Han River  ' }), 4, t)).toBe('Han River')
  })

  it('the image is next/image fill object-cover, src through mediaPath, sizes by column width and image ratio', () => {
    const p = photo(1)
    const { container, rerender } = render(<GalleryGrid photos={[p]} />)

    const img = container.querySelector('img')!
    expect(sourceOf(img)).toBe(mediaPath(p.image))
    expect(classesOf(img)).toContain('object-cover')
    // `fill`: the image covers the whole square cell, the cell decides the size and not the image.
    expect(img.style.position).toBe('absolute')
    expect(img).toHaveAttribute('sizes', tileSizes(p.image, 'wide'))
    // The grid does not compete for bandwidth with the top of the page unless asked otherwise.
    expect(img).toHaveAttribute('loading', 'lazy')
    expect(img).not.toHaveAttribute('fetchpriority')

    rerender(<GalleryGrid photos={[p]} width="prose" />)
    expect(container.querySelector('img')).toHaveAttribute('sizes', tileSizes(p.image, 'prose'))
  })

  it('sizes multiplies the cell width by the width/height ratio (clamped 1–2.5): a wide image cropped by object-cover shrinks by height', () => {
    // A 20rem cell with a 4:3 image needs a ~27rem wide version; sizes = the cell width (the earlier version) made a 2× screen get a
    // 640w file for a 318px cell and scale the image up 1.3–1.6 times.
    expect(tileSizes({ width: 1600, height: 1200 }, 'wide')).toBe('(min-width: 640px) 27rem, 44vw')
    expect(tileSizes({ width: 1600, height: 1000 }, 'wide')).toBe('(min-width: 640px) 32rem, 53vw')
    expect(tileSizes({ width: 1600, height: 1200 }, 'prose')).toBe('(min-width: 640px) 20rem, 44vw')
    // Square and portrait: the width is the limit, keep the cell width.
    expect(tileSizes({ width: 1200, height: 1200 }, 'wide')).toBe('(min-width: 640px) 20rem, 33vw')
    expect(tileSizes({ width: 1800, height: 2400 }, 'wide')).toBe('(min-width: 640px) 20rem, 33vw')
    expect(tileSizes({ width: 1800, height: 2400 }, 'prose')).toBe('(min-width: 640px) 15rem, 33vw')
    // Panorama: ceiling 2.5, not pulled to the 3840w version. A broken size: treated as square, not NaN.
    expect(tileSizes({ width: 6000, height: 1000 }, 'wide')).toBe('(min-width: 640px) 50rem, 83vw')
    expect(tileSizes({ width: 0, height: 0 }, 'wide')).toBe('(min-width: 640px) 20rem, 33vw')
    // column (the text column of /about): ~12.7rem from 1024px, as wide as wide when the page is one column.
    expect(tileSizes({ width: 1200, height: 1200 }, 'column')).toBe('(min-width: 1024px) 13rem, (min-width: 640px) 20rem, 33vw')
    expect(tileSizes({ width: 1600, height: 1200 }, 'column')).toBe('(min-width: 1024px) 17rem, (min-width: 640px) 27rem, 44vw')

    // Each cell follows its own image.
    const { container } = render(<GalleryGrid photos={[photo(1), photo(2, { width: 1800, height: 2400 })]} />)
    const [landscape, portrait] = Array.from(container.querySelectorAll('img'))
    expect(landscape).toHaveAttribute('sizes', '(min-width: 640px) 27rem, 44vw')
    expect(portrait).toHaveAttribute('sizes', '(min-width: 640px) 20rem, 33vw')
  })

  it('browse and band: the exact sizes strings, the clauses from the LARGEST min-width to the smallest', () => {
    const square = { width: 1200, height: 1200 }
    // browse: 16.5rem from xl (4 columns), 20.5rem from lg (3 columns), 20rem from sm, a third of the screen below.
    expect(tileSizes(square, 'browse')).toBe(
      '(min-width: 1280px) 16.5rem, (min-width: 1024px) 20.5rem, (min-width: 640px) 20rem, 33vw',
    )
    // band: 14rem from lg (6 columns), 20rem from sm.
    expect(tileSizes(square, 'band')).toBe('(min-width: 1024px) 14rem, (min-width: 640px) 20rem, 33vw')

    // With the ratio factor (4:3 = 1.333): every clause is multiplied, rounded up to the next half rem; vw rounds up to a whole.
    expect(tileSizes({ width: 1600, height: 1200 }, 'browse')).toBe(
      '(min-width: 1280px) 22rem, (min-width: 1024px) 27.5rem, (min-width: 640px) 27rem, 44vw',
    )
    expect(tileSizes({ width: 1600, height: 1200 }, 'band')).toBe('(min-width: 1024px) 19rem, (min-width: 640px) 27rem, 44vw')
    // Panorama: the ceiling 2.5 applies to every clause.
    expect(tileSizes({ width: 6000, height: 1000 }, 'browse')).toBe(
      '(min-width: 1280px) 41.5rem, (min-width: 1024px) 51.5rem, (min-width: 640px) 50rem, 83vw',
    )
    expect(tileSizes({ width: 0, height: 0 }, 'band')).toBe('(min-width: 1024px) 14rem, (min-width: 640px) 20rem, 33vw')

    // Clause-order pin: the browser takes the first matching clause, so a smaller min-width before a larger one would win everywhere.
    for (const width of ['browse', 'band', 'column'] as const) {
      const mins = [...tileSizes(square, width).matchAll(/min-width: (\d+)px/g)].map((m) => Number(m[1]))
      expect(mins, width).toEqual([...mins].sort((a, b) => b - a))
    }
    expect(TILE_WIDTH.browse).toEqual({ rem: 20, vw: 33, lgRem: 20.5, xlRem: 16.5 })
    expect(TILE_WIDTH.band).toEqual({ rem: 20, vw: 33, lgRem: 14 })

    // The image carries the string of its own grid.
    const { container } = render(<GalleryGrid photos={[photo(1)]} width="browse" columns={4} />)
    expect(container.querySelector('img')).toHaveAttribute('sizes', tileSizes(photo(1).image, 'browse'))
  })

  it('eager={3}: the first row loads immediately, the first cell with high priority, the rest still lazy, no preload', () => {
    const photos = [1, 2, 3, 4, 5].map((n) => photo(n))
    const { container } = render(<GalleryGrid photos={photos} eager={3} />)

    const imgs = Array.from(container.querySelectorAll('img'))
    expect(imgs.map((img) => img.getAttribute('loading'))).toEqual(['eager', 'eager', 'eager', 'lazy', 'lazy'])
    expect(imgs.map((img) => img.getAttribute('fetchpriority'))).toEqual(['high', null, null, null, null])
    // next/image `preload` inserts <link rel="preload"> into <head>; the Next 16 docs say not to
    // use it together with fetchPriority.
    expect(document.head.querySelector('link[rel="preload"][as="image"]')).toBeNull()
  })

  it('square cell rounded-md, hairline border changing color on hover, dominantColor background while the image loads', () => {
    const { container } = render(<GalleryGrid photos={[photo(1)]} />)

    const link = container.querySelector('a')!
    const frame = container.querySelector('img')!.parentElement!
    expect(frame.parentElement).toBe(link)
    expect(classesOf(link)).toEqual(
      expect.arrayContaining(['group', 'block', 'focus-visible:outline-2', 'focus-visible:outline-brand']),
    )
    expect(classesOf(frame)).toEqual(
      expect.arrayContaining([
        'relative',
        'block',
        'aspect-square',
        'overflow-hidden',
        'rounded-md',
        'border',
        'border-neutral-200',
        'dark:border-neutral-800',
        'group-hover:border-brand',
        'transition-colors',
        'duration-[120ms]',
        'motion-reduce:transition-none',
      ]),
    )
    // jsdom normalizes hex to rgb().
    expect(frame.style.backgroundColor).toBe('rgb(90, 107, 124)')
  })

  it('only uses dominantColor when it is exactly #rrggbb', () => {
    for (const dominantColor of [null, 'red', '#5a6b7c; position: fixed', '#5a6b7']) {
      const { container, unmount } = render(<GalleryGrid photos={[photo(1, { dominantColor })]} />)
      const frame = container.querySelector('img')!.parentElement!
      expect(frame.style.backgroundColor, String(dominantColor)).toBe('')
      expect(frame.getAttribute('style') ?? '', String(dominantColor)).not.toContain('position')
      unmount()
    }

    const { container } = render(<GalleryGrid photos={[photo(1, { dominantColor: '#a1b2c3' })]} />)
    expect(container.querySelector('img')!.parentElement!.style.backgroundColor).toBe('rgb(161, 178, 195)')
  })

  it('each cell carries its index in data-gallery-index, in array order', () => {
    const { container } = render(<GalleryGrid photos={[photo(1), photo(2), photo(3)]} />)

    expect(TILE_INDEX_ATTRIBUTE).toBe('data-gallery-index')
    const indexes = Array.from(container.querySelectorAll('a')).map((a) => a.getAttribute(TILE_INDEX_ATTRIBUTE))
    expect(indexes).toEqual(['0', '1', '2'])
  })

  it('with no images it renders nothing, not even an empty <ul>', () => {
    const { container } = render(<GalleryGrid photos={[]} />)

    expect(container.innerHTML).toBe('')
  })

  it('no text in a cell besides the accessible name of the image', () => {
    const { container } = render(<GalleryGrid photos={[photo(1)]} />)

    // The caption and shooting date belong to the viewer, they do not squeeze into the grid.
    const tile = within(container.querySelector('li')!)
    expect(tile.queryByText(/./)).toBeNull()
  })

  describe('layout="square" (default) portrait crop', () => {
    it('anchors a portrait near the top so heads are not cut, centers everything else', () => {
      const { container } = render(
        <GalleryGrid photos={[photo(1, { width: 1800, height: 2400 }), photo(2), photo(3, { width: 1200, height: 1200 })]} />,
      )
      const imgs = Array.from(container.querySelectorAll('img'))
      expect(classesOf(imgs[0])).toContain('object-[50%_28%]')
      expect(classesOf(imgs[1])).toContain('object-center')
      expect(classesOf(imgs[2])).toContain('object-center')
      // The default layout is still the square grid, with no inline ratio.
      expect(container.querySelector('ul')).toHaveClass('grid')
      expect(container.querySelector('li')!.getAttribute('style')).toBeNull()
    })
  })

  describe('layout="justified"', () => {
    const mixed = [
      photo(1, { width: 1800, height: 2400 }), // 3:4
      photo(2, { width: 1600, height: 1200 }), // 4:3
      photo(3, { width: 1920, height: 1080 }), // 16:9
      photo(4, { width: 9000, height: 1000 }), // panorama, clamped
      photo(5, { width: 800, height: 6000 }), // very tall, clamped
      photo(6, { width: 0, height: 0 }), // unknown size
    ]

    it('is a wrapping flex list; each cell grows by its ratio and has its ratio as basis, in reading order', () => {
      const { container } = render(<GalleryGrid photos={mixed} layout="justified" />)

      const list = container.querySelector('ul')!
      expect(classesOf(list)).toEqual(expect.arrayContaining(['flex', 'flex-wrap', 'gap-1', 'sm:gap-2']))
      expect(classesOf(list)).not.toContain('grid')
      const cells = Array.from(list.querySelectorAll<HTMLElement>(':scope > li:not([aria-hidden])'))
      expect(cells).toHaveLength(6)
      expect(cells[0].style.flexGrow).toBe('0.75')
      expect(cells[0].style.flexBasis).toBe('calc(0.75 * var(--row-h))')
      expect(cells[0].style.maxWidth).toBe(`calc(${0.75 * JUSTIFIED_MAX_GROWTH} * var(--row-h))`)
      expect(cells[1].style.flexGrow).toBe(String(4 / 3))
      // A landscape is capped by the `--grow` variable (large on a phone so a lone landscape fills the row), a portrait is not.
      expect(cells[1].style.maxWidth).toBe(`calc(${4 / 3} * var(--grow) * var(--row-h))`)
      // The frame keeps the same ratio, so object-cover crops nothing.
      const frames = Array.from(list.querySelectorAll<HTMLElement>('a > span'))
      expect(frames[0].style.aspectRatio).toBe('0.75 / 1')
      expect(classesOf(frames[0])).not.toContain('aspect-square')
      // Index order is the data-gallery-index order.
      const indexes = Array.from(list.querySelectorAll('a')).map((a) => a.getAttribute(TILE_INDEX_ATTRIBUTE))
      expect(indexes).toEqual(['0', '1', '2', '3', '4', '5'])
    })

    it('clamps the ratio to 0.5–2.5 and falls back to 1 for an unknown size', () => {
      expect(layoutRatio({ width: 9000, height: 1000 })).toBe(2.5)
      expect(layoutRatio({ width: 800, height: 6000 })).toBe(0.5)
      expect(layoutRatio({ width: 0, height: 0 })).toBe(1)
      expect(layoutRatio({ width: 1600, height: 1200 })).toBeCloseTo(4 / 3)

      const { container } = render(<GalleryGrid photos={mixed} layout="justified" />)
      const cells = Array.from(container.querySelectorAll<HTMLElement>(':scope ul > li:not([aria-hidden])'))
      expect(cells[3].style.flexGrow).toBe('2.5')
      expect(cells[4].style.flexGrow).toBe('0.5')
      expect(cells[5].style.flexGrow).toBe('1')
    })

    it('has a trailing filler that is hidden from assistive tech, not focusable and has no name', () => {
      const { container } = render(<GalleryGrid photos={mixed} layout="justified" />)

      const items = container.querySelectorAll('ul > li')
      const filler = items[items.length - 1] as HTMLElement
      expect(filler).toHaveAttribute('aria-hidden', 'true')
      expect(filler).toHaveAttribute('role', 'presentation')
      expect(filler.textContent).toBe('')
      expect(filler.querySelector('a, button, [tabindex]')).toBeNull()
      // No share of the last row on a phone (a lone landscape fills it), about one photo's share from sm.
      expect(filler).toHaveClass('grow-0', 'sm:grow-[2]')
      expect(filler.style.flexBasis).toMatch(/^0(px)?$/)
      // Only the photos are exposed as links.
      expect(screen.getAllByRole('link')).toHaveLength(6)
    })

    it('sizes follow the basis width at each breakpoint and never exceed the screen on a phone', () => {
      expect(justifiedSizes({ width: 1800, height: 2400 })).toBe(
        '(min-width: 1024px) 14rem, (min-width: 640px) 11.5rem, min(100vw, 9rem)',
      )
      // A landscape can wrap onto a phone row alone and then fills the width, so its phone clause is the screen width.
      expect(justifiedSizes({ width: 1600, height: 1200 })).toBe('(min-width: 1024px) 24.5rem, (min-width: 640px) 20rem, 100vw')
      // The panorama uses the clamped ratio, the clauses go from the largest min-width to the smallest.
      const mins = [...justifiedSizes({ width: 9000, height: 1000 }).matchAll(/min-width: (\d+)px/g)].map((m) => Number(m[1]))
      expect(mins).toEqual([1024, 640])

      const { container } = render(<GalleryGrid photos={mixed} layout="justified" />)
      expect(container.querySelector('img')).toHaveAttribute('sizes', justifiedSizes(mixed[0].image))
    })

    it('keeps the rounded frame, placeholder colour, eager loading and the real link', () => {
      const { container } = render(<GalleryGrid photos={mixed} layout="justified" eager={2} />)

      const imgs = Array.from(container.querySelectorAll('img'))
      expect(imgs.map((i) => i.getAttribute('loading'))).toEqual(['eager', 'eager', 'lazy', 'lazy', 'lazy', 'lazy'])
      expect(imgs[0]).toHaveAttribute('fetchpriority', 'high')
      const frame = imgs[0].parentElement!
      expect(classesOf(frame)).toEqual(
        expect.arrayContaining(['rounded-md', 'border', 'group-hover:border-brand', 'overflow-hidden']),
      )
      expect(frame.style.backgroundColor).toBe('rgb(90, 107, 124)')
      expect(frame.parentElement).toHaveAttribute('href', mediaPath(mixed[0].image))
      expect(classesOf(imgs[0])).toContain('object-cover')
    })
  })
})
